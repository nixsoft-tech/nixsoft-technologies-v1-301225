export const getServiceBySlug = (slug: string): OfferingData | undefined =>
  SERVICES_DATA.find((s) => s.slug === slug);

/**
 * Resolve an old-site /service/<slug> URL to its current service, matching
 * either the canonical slug or a legacy alias. Used for 301 redirects.
 */
export const getServiceBySlugOrAlias = (slug: string): OfferingData | undefined =>
  SERVICES_DATA.find((s) => s.slug === slug || (s.legacyAliases?.includes(slug) ?? false));

export const getServicesByCategory = (category: string): OfferingData[] =>
  SERVICES_DATA.filter((s) => s.category === category);

/** A service's banner: its own image if set, otherwise its category's. */
export const getServiceImage = (service: OfferingData): string | undefined =>
  service.image ?? SERVICE_CATEGORIES.find((c) => c.id === service.category)?.image;

/** Alt text for a service's banner, falling back to its category's. */
export const getServiceImageAlt = (service: OfferingData): string =>
  service.imageAlt ?? SERVICE_CATEGORIES.find((c) => c.id === service.category)?.imageAlt ?? '';
